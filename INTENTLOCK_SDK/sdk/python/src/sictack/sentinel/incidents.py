"""
SICTACK SENTINEL — Security Incident Management (Phase 4C).

Manages formal security incidents generated by multi-agent threat detections (MAD-001 through MAD-010)
and severe behavioral telemetry anomalies. Tracks incident lifecycles:
DETECTED -> INVESTIGATING -> CONTAINED -> RESOLVED.
"""

from __future__ import annotations

import uuid
from collections import defaultdict
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

from sictack.sentinel.models import DetectionSeverity
from sictack.sentinel.multi_agent_models import (
    IncidentSeverity,
    IncidentStatus,
    MultiAgentDetectionResult,
    SecurityIncident,
)


class SecurityIncidentManager:
    """
    Manages tenant-isolated security incidents and containment lifecycle.
    """

    def __init__(self) -> None:
        # org_id -> incident_id -> SecurityIncident
        self._incidents: Dict[str, Dict[str, SecurityIncident]] = defaultdict(dict)

    def create_incident_from_detection(
        self,
        org_id: str,
        detection: MultiAgentDetectionResult,
    ) -> SecurityIncident:
        """Create a new incident triggered by a multi-agent detection result."""
        severity_map = {
            DetectionSeverity.LOW: IncidentSeverity.LOW,
            DetectionSeverity.MEDIUM: IncidentSeverity.MEDIUM,
            DetectionSeverity.HIGH: IncidentSeverity.HIGH,
            DetectionSeverity.CRITICAL: IncidentSeverity.CRITICAL,
        }
        mapped_severity = severity_map.get(detection.severity, IncidentSeverity.HIGH)

        affected = [detection.primary_agent_id]
        for aid in detection.correlated_agent_ids:
            if aid not in affected:
                affected.append(aid)

        sessions = [detection.session_id] if detection.session_id else []

        incident = SecurityIncident(
            incident_id=f"inc_{uuid.uuid4().hex[:12]}",
            org_id=org_id,
            title=f"Security Alert: {detection.rule_name} ({detection.rule_id})",
            severity=mapped_severity,
            status=IncidentStatus.DETECTED,
            trigger_rule_id=detection.rule_id,
            affected_agent_ids=affected,
            session_ids=sessions,
            summary=detection.explanation,
            evidence_trail=[
                {
                    "timestamp": detection.timestamp.isoformat(),
                    "reason_code": detection.reason_code,
                    "confidence": detection.confidence,
                    "evidence": detection.evidence,
                    "recommended_action": detection.recommended_action,
                }
            ],
            created_at=datetime.now(timezone.utc),
            updated_at=datetime.now(timezone.utc),
        )

        self._incidents[org_id][incident.incident_id] = incident
        return incident

    def create_incident(
        self,
        *,
        org_id: str,
        title: str,
        trigger_rule_id: str,
        severity: IncidentSeverity = IncidentSeverity.HIGH,
        affected_agent_ids: Optional[List[str]] = None,
        session_ids: Optional[List[str]] = None,
        summary: str = "",
        evidence: Optional[Dict[str, Any]] = None,
    ) -> SecurityIncident:
        """Create an incident manually or via API."""
        incident = SecurityIncident(
            incident_id=f"inc_{uuid.uuid4().hex[:12]}",
            org_id=org_id,
            title=title,
            severity=severity,
            status=IncidentStatus.DETECTED,
            trigger_rule_id=trigger_rule_id,
            affected_agent_ids=affected_agent_ids or [],
            session_ids=session_ids or [],
            summary=summary,
            evidence_trail=[evidence] if evidence else [],
            created_at=datetime.now(timezone.utc),
            updated_at=datetime.now(timezone.utc),
        )
        self._incidents[org_id][incident.incident_id] = incident
        return incident

    def get_incident(self, org_id: str, incident_id: str) -> Optional[SecurityIncident]:
        """Retrieve a specific incident by ID within a tenant."""
        return self._incidents.get(org_id, {}).get(incident_id)

    def list_incidents(
        self,
        org_id: str,
        status: Optional[IncidentStatus] = None,
        severity: Optional[IncidentSeverity] = None,
        agent_id: Optional[str] = None,
    ) -> List[SecurityIncident]:
        """List tenant incidents with optional filtering."""
        incidents = list(self._incidents.get(org_id, {}).values())

        if status:
            incidents = [i for i in incidents if i.status == status]
        if severity:
            incidents = [i for i in incidents if i.severity == severity]
        if agent_id:
            incidents = [i for i in incidents if agent_id in i.affected_agent_ids]

        # Order by newest first
        return sorted(incidents, key=lambda i: i.created_at, reverse=True)

    def update_status(
        self,
        org_id: str,
        incident_id: str,
        new_status: IncidentStatus,
        evidence_note: Optional[str] = None,
    ) -> Optional[SecurityIncident]:
        """Transition incident status."""
        inc = self.get_incident(org_id, incident_id)
        if not inc:
            return None

        inc.status = new_status
        inc.updated_at = datetime.now(timezone.utc)
        if evidence_note:
            inc.evidence_trail.append({
                "timestamp": inc.updated_at.isoformat(),
                "event": f"Status updated to {new_status.value}",
                "note": evidence_note,
            })
        return inc

    def contain_incident(
        self,
        org_id: str,
        incident_id: str,
        action: str,
        operator: Optional[str] = None,
    ) -> Optional[SecurityIncident]:
        """Apply containment remediation to an incident."""
        inc = self.get_incident(org_id, incident_id)
        if not inc:
            return None

        now = datetime.now(timezone.utc)
        inc.status = IncidentStatus.CONTAINED
        inc.containment_action_taken = action
        inc.updated_at = now
        inc.evidence_trail.append({
            "timestamp": now.isoformat(),
            "event": "CONTAINMENT_ENFORCED",
            "action": action,
            "operator": operator or "AUTONOMOUS_SENTINEL",
        })
        return inc

    def resolve_incident(
        self,
        org_id: str,
        incident_id: str,
        resolved_by: str,
        notes: str,
    ) -> Optional[SecurityIncident]:
        """Formally resolve and close an incident."""
        inc = self.get_incident(org_id, incident_id)
        if not inc:
            return None

        now = datetime.now(timezone.utc)
        inc.status = IncidentStatus.RESOLVED
        inc.resolved_at = now
        inc.resolved_by = resolved_by
        inc.resolution_notes = notes
        inc.updated_at = now
        inc.evidence_trail.append({
            "timestamp": now.isoformat(),
            "event": "INCIDENT_RESOLVED",
            "resolved_by": resolved_by,
            "notes": notes,
        })
        return inc
